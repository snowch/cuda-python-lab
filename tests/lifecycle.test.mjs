import test from 'node:test';
import assert from 'node:assert/strict';
import {cp,mkdtemp,readFile,writeFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {pathToFileURL} from 'node:url';
import {buildOffline} from '../scripts/offline.mjs';
import {launchChromium,serveBuild} from './browser-support.mjs';
const editor=page=>page.getByRole('textbox',{name:'Python program source'});
const ready=page=>page.waitForFunction(()=>window.cudaPythonCodeRunner?.state==='ready',null,{timeout:90000});
const finished=page=>page.locator('#run-status').filter({hasText:'Ran in GPGPU-Sim.'}).waitFor({timeout:90000});
async function replace(page,text){await editor(page).press('ControlOrMeta+a');await page.keyboard.insertText(text);}
async function lesson(page,slug){await page.evaluate(slug=>location.hash='lesson/'+slug,slug);await editor(page).waitFor();}

test('manual startup introduces the runner once, retains it between lessons, and releases memory without losing work',{timeout:150000},async t=>{
 const url=await serveBuild(t,{prefix:'/cuda-python-lab/'}),browser=await launchChromium(t);
 const page=await browser.newPage({viewport:{width:390,height:850}}),errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto(url+'#lesson/first-value');await editor(page).waitFor();
 assert.deepEqual(await page.locator('.site-nav button').evaluateAll(elements=>elements.map(el=>el.id)),['code-runner-open','app-status-open','theme']);
 await page.locator('#code-runner-open').click();await page.locator('[data-runner-start]').click();
 const intro=page.locator('#code-runner-intro-dialog');await intro.waitFor({state:'visible',timeout:2000});
 assert.match(await intro.textContent(),/CPU and memory/);
 assert.equal(await intro.evaluate(el=>el.matches(':modal')),true);
 await page.locator('[data-intro-back]').click();await ready(page);
 assert.equal(await page.locator('#run-output').textContent(),'');
 assert.equal(await page.evaluate(()=>window.cudaPythonCodeRunner.completedRuns),0);
 assert.ok(await page.evaluate(()=>window.cudaPythonCodeRunner.wasmBytes>0),'report measured resident WASM memory');
 await page.locator('#run').click();await finished(page);assert.equal(await intro.isVisible(),false);
 assert.equal(await page.locator('#run-output').textContent(),'out = [42.0]');
 const firstBoots=await page.evaluate(()=>window.cudaPythonCodeRunner.boots);
 await lesson(page,'vector-add');await page.locator('#run').click();await finished(page);
 assert.equal(await page.evaluate(()=>window.cudaPythonCodeRunner.boots),firstBoots);
 await lesson(page,'first-value');assert.equal(await page.locator('#run-output').textContent(),'out = [42.0]');
 await page.locator('#prediction').fill('The CPU prints 7');
 await page.locator('#complete').click();
 await page.locator('#code-runner-open').click();await page.locator('#code-runner-timeout').selectOption('15');
 await page.locator('[data-runner-free]').click();assert.equal(await page.locator('#run-output').textContent(),'out = [42.0]');
 assert.equal(await page.evaluate(()=>window.cudaPythonCodeRunner.wasmBytes),0);
 await page.locator('[data-runner-close]').click();
 await page.reload();await editor(page).waitFor();assert.equal(await page.locator('#prediction').inputValue(),'The CPU prints 7');
 assert.equal(await page.locator('#complete').isChecked(),true);assert.equal(await page.locator('#run-output').textContent(),'out = [42.0]');
 await page.locator('#code-runner-open').click();assert.equal(await page.locator('#code-runner-timeout').inputValue(),'15');
 await page.keyboard.press('Escape');assert.equal(await page.locator('#code-runner-open').evaluate(el=>el===document.activeElement),true);
 for(const width of [360,390,768,1280])for(const theme of ['light','dark']){
  await page.setViewportSize({width,height:850});await page.emulateMedia({colorScheme:theme});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`${width}/${theme}`);
  await page.locator('#app-status-open').click();assert.equal(await page.locator('#app-status-dialog').evaluate(el=>el.matches(':modal')),true);await page.keyboard.press('Escape');
 }
 assert.deepEqual(errors,[]);
});

